#!/usr/bin/env node
/**
 * Stage 0 — Capture Agent Observability Baseline
 *
 * Bundles and runs tests/live-e2e/agent-baseline-harness.ts (real AgentEngine +
 * loopback test-double provider), then writes the genuine metrics to
 * docs/AGENT_BASELINE.md as the regression canary that gates every later stage.
 *
 * Usage: npm run baseline:capture
 * Brand: Ty-Code
 */

import fs from 'node:fs/promises';
import fsSync from 'node:fs';
import path from 'node:path';
import { execSync } from 'node:child_process';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { build } from 'esbuild';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const projectRoot = path.resolve(__dirname, '..');
const bundleDir = path.join(projectRoot, '.tmp-agent-baseline');
const harnessTs = path.join(projectRoot, 'tests', 'live-e2e', 'agent-baseline-harness.ts');
const harnessCjs = path.join(bundleDir, 'agent-baseline-harness.cjs');

async function run() {
  console.log('🧪 Stage 0 — capturing the real agent observability baseline…\n');
  await fs.mkdir(bundleDir, { recursive: true });

  try {
    await build({
      entryPoints: [harnessTs],
      outfile: harnessCjs,
      bundle: true,
      platform: 'node',
      format: 'cjs',
      target: 'node20',
      external: ['electron', 'node-pty', 'simple-git', 'playwright-core', 'electron-updater']
    });

    const mod = await import(pathToFileURL(harnessCjs).href);
    const runAgentBaseline = mod.runAgentBaseline || mod.default?.runAgentBaseline;
    if (typeof runAgentBaseline !== 'function') {
      throw new Error('Baseline harness did not export runAgentBaseline()');
    }
    const metrics = await runAgentBaseline(3);

    let gitCommit = 'unknown';
    try {
      gitCommit = execSync('git rev-parse HEAD', { encoding: 'utf-8', cwd: projectRoot }).trim() || 'unknown';
    } catch {
      // keep 'unknown'
    }

    const doc = `# Agent Harness & Loop — Performance Baseline (Stage 0 Canary)

> Generated by \`npm run baseline:capture\` on ${new Date().toISOString()}
> Git commit: \`${gitCommit}\`
> Source: real \`AgentEngine\` run over a loopback SSE test-double provider (real TCP + real disk), averaged across ${metrics.repeats} repeats of a representative multi-file, ~9-tool task.

This file is the regression canary for the Agentic Harness & Loop improvement plan.
Every later stage must show **no degradation** against these numbers. Enforced by
\`scripts/no-agent-performance-regression.mjs\` (Stage 4a) added to \`npm run guards\`.

## Baseline Metrics

| Metric | Value | Measured from |
| --- | --- | --- |
| Average iterations (model round-trips) for the standard multi-file task | ${metrics.avgIterations} | \`generateReport().llmCalls.count\` |
| Tool-call failure rate (per 100 executed calls) | ${metrics.toolCallFailureRatePer100} | \`generateReport().toolCalls.perTool\` failure/total |
| Wall time for the representative ~9-tool task (median, ms) | ${metrics.medianWallTimeMs} | end-to-end \`AgentEngine.run()\` timing |
| Token efficiency (tokens per successful edit) | ${metrics.tokensPerSuccessfulEdit} | \`llmCalls.tokensIn + tokensOut\` / successful edit tools |

## Supporting Counts
- Total executed tool calls across repeats: ${metrics.totalToolCalls}
- Total successful edits across repeats: ${metrics.successfulEdits}
- Repeats: ${metrics.repeats}

## Thresholds (defaults, overridable via \`.tycode-perf-thresholds.json\` or \`TYCODE_PERF_THRESHOLDS\`)
- Iterations: fail if current > baseline + 20%
- Tool-call failure rate: fail if current > baseline + 10%
- Wall time: fail if current > baseline + 30%

## Notes
- Captured BEFORE any Stage 1 code changes; reflects the current iteration
  double-counting behavior (Stage 1a will reduce the iteration figure).
- The provider is a test harness, not a product code path; no fixture replies are
  baked into \`src/**\` (verified by \`npm run guards\`).
`;

    const outPath = path.join(projectRoot, 'docs', 'AGENT_BASELINE.md');
    await fs.writeFile(outPath, doc, 'utf8');
    console.log(`\n✓ Wrote baseline canary: docs/AGENT_BASELINE.md`);
    console.log(JSON.stringify(metrics, null, 2));
  } finally {
    try {
      await fs.rm(bundleDir, { recursive: true, force: true });
    } catch {
      // ignore
    }
  }
}

if (!fsSync.existsSync(harnessTs)) {
  console.error(`Baseline harness not found at ${harnessTs}`);
  process.exit(1);
}

run().catch((err) => {
  console.error('❌ Baseline capture failed:', err);
  process.exit(1);
});
